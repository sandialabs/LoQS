def _check_shot_features(
    results, collect_shot_data_args, expected_outcomes, verbose=False
):
    """Check collected shot features against expected values, replicating
    the removed fttools.test_program_output's pass/fail logic locally so
    this file no longer depends on fttools internals. Each collect_shot_data_args
    entry is a HistoryDataCollector-compatible spec: a plain (key, indices) tuple,
    or a dict also supporting frame_filter to select by log text instead of a
    raw frame index."""
    for args, expected in zip(collect_shot_data_args, expected_outcomes):
        out = HistoryDataCollector.from_raw(args).collect(results)[-1]
        if out != expected:
            if verbose:
                print(f"Output:   {out}")
                print(f"Expected: {expected}")
            return False
    return True


# The workflow tests' stacks and noiseless outcomes. The PyGSTi model cannot
# produce STIM reps, so that combination is not generated.
NONFT_STACK_OUTCOMES = [
    ([("Non-FT Logical X Measure", "L0")], 1),
    ([("Z", "L0"), ("Non-FT Logical X Measure", "L0")], 0),
    ([("H", "L0"), ("Non-FT Logical Z Measure", "L0")], 1),
    ([("H", "L0"), ("X", "L0"), ("Non-FT Logical Z Measure", "L0")], 0),
]
FT_STACK_OUTCOMES = [
    ([("FT Logical X Measure", "L0")], 1),
    (
        [
            ("Z", "L0"),
            ("Flagged QEC", "L0"),
            ("FT Logical X Measure", "L0"),
        ],
        0,
    ),
]
# The supported (state, model, circuit) combinations other than
# STIM + Dict + List, which every stack outcome already runs on.
OTHER_BACKEND_COMBOS = [
    (QSimQuantumState, PyGSTiNoiseModel, PyGSTiPhysicalCircuit),
    (QSimQuantumState, PyGSTiNoiseModel, ListPhysicalCircuit),
    (QSimQuantumState, DictNoiseModel, PyGSTiPhysicalCircuit),
    (QSimQuantumState, DictNoiseModel, ListPhysicalCircuit),
    (STIMQuantumState, DictNoiseModel, PyGSTiPhysicalCircuit),
]


class Test5QCodepack:

    @staticmethod
    def _create_program(circuit_backend, model_backend, state_backend):
        code_5q = codepack_5_1_3.create_qec_code(
            circuit_backend=circuit_backend
        )

        # Define the physical qubit labels for our system here
        qubits = ["A0", "A1"] + [f"D{i+2}" for i in range(5)]

        if state_backend == QSimQuantumState:
            gaterep = QSimSuperopGateRep
        else:
            gaterep = StimCircuitGateRep

        ideal_model = codepack_5_1_3.create_ideal_model(
            qubits, gaterep=gaterep, model_backend=model_backend
        )

        state_type = state_backend
        patch_types = {"5Q": code_5q}

        # Stack
        # The "Init *" instructions will be generated by the QuantumProgram based on the values
        # of state_type and patch_types below
        stack = [
            {
                "instruction": "Init State",
                "state": len(qubits),
                "qubit_labels": qubits,
            },  # Autogenerated from state_type
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": qubits,
            },  # Autogenerated from patch_types. Note that 5Q here must be a key into the patch_types dict below
            ("Non-FT Minus Prep", "L0"),
            ("Non-FT Logical X Measure", "L0"),
        ]

        return QuantumProgram(
            stack,
            default_noise_model=ideal_model,
            state_type=state_type,
            patch_types=patch_types,
            name="Prep minus, measure X",
        )

    @classmethod
    def setup_class(cls):
        cls.program = cls._create_program(
            PyGSTiPhysicalCircuit, PyGSTiNoiseModel, QSimQuantumState
        )
        cls.stim_program = cls._create_program(
            PyGSTiPhysicalCircuit, DictNoiseModel, STIMQuantumState
        )
        cls.qubits = ["A0", "A1"] + [f"D{i+2}" for i in range(5)]

    # Each (state, model, circuit) combination runs one workflow, and each
    # workflow runs on STIM with the Dict model and the List circuit.
    @pytest.mark.parametrize(
        "state_backend, model_backend, circuit_backend, stack_outcome",
        [
            (STIMQuantumState, DictNoiseModel, ListPhysicalCircuit, so)
            for so in NONFT_STACK_OUTCOMES
        ]
        + [
            (state, model, circuit, NONFT_STACK_OUTCOMES[0])
            for state, model, circuit in OTHER_BACKEND_COMBOS
        ],
    )
    def test_nonft_workflow(
        self, state_backend, model_backend, circuit_backend, stack_outcome
    ):
        ref_program = self._create_program(
            circuit_backend, model_backend, state_backend
        )

        stack = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            ("Non-FT Minus Prep", "L0"),
        ]
        stack += stack_outcome[0]

        program = QuantumProgram.from_quantum_program(ref_program, stack)
        program_results = program.run()
        assert (
            program_results.collect_shot_data("logical_measurement", -1)[0]
            == stack_outcome[1]
        )

