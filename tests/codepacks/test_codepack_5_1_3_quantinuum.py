    # Fixed faults reaching the FT measurement's feed-forward branches (parts
    # II and III). Outcomes depend on the schedule, so only the flag is checked.
    @pytest.mark.parametrize(
        "part, fault",
        [
            ("II", (2, "Gxpi", 1)),
            ("III", (0, "Gxpi", 0)),
            ("III", (2, "Gxpi", 1)),
        ],
    )
    def test_ft_measure_fault_branch_smoke(self, part, fault):
        def ideal_apply_fn_for(flag, inferred):
            return Instruction(
                lambda: Frame({flag: 0, inferred: 1}),
                serialized_apply_fn="",  # Hack, we won't need to serialize
            )

        global_instructions = {
            "Ideal Part I Feed-Forward": ideal_apply_fn_for(
                "F1", "inferred_M1"
            ),
            "Ideal Part II Feed-Forward": ideal_apply_fn_for(
                "F2", "inferred_M2"
            ),
        }
        stack = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            ("FT Minus Prep", "L0"),
            ("FT Logical X Measure Part I Circuit", "L0"),
            ("Ideal Part I Feed-Forward", None),
            ("FT Logical X Measure Part II Circuit", "L0"),
        ]
        faulted = {
            "instruction": f"FT Logical X Measure Part {part} Circuit",
            "patch_label": "L0",
            "error_injections": [fault],
        }
        if part == "II":
            stack[-1] = faulted
            stack.append(("FT Logical X Measure Part II Feed-Forward", "L0"))
            flag = "F2"
        else:
            stack += [
                ("Ideal Part II Feed-Forward", None),
                faulted,
                ("FT Logical X Measure Part III Feed-Forward", "L0"),
            ]
            flag = "F3"

        program = QuantumProgram.from_quantum_program(
            self.stim_program,
            stack,
            global_instructions=global_instructions,
            name=f"FT measure part {part} fault branch",
        )
        results = program.run(num_shots=3)
        for shot in range(3):
            assert any(flag in frame for frame in results.shot_histories[shot])

    # One fixed fault per flagged-check branch (flag raised; syndrome without a
    # flag), checking only that a logical outcome is recorded.
    @pytest.mark.parametrize("fault", [(2, "Gxpi", 1), (0, "Gxpi", 0)])
    def test_flagged_qec_fault_branch_smoke(self, fault):
        stack = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            ("FT Minus Prep", "L0"),
            {
                "instruction": "Flagged XZZXI Check",
                "patch_label": "L0",
                "error_injections": [fault],
            },
            ("Flagged XZZXI Feed-Forward", "L0"),
            ("FT Logical X Measure", "L0"),
        ]
        program = QuantumProgram.from_quantum_program(
            self.stim_program, stack, name="Flagged QEC fault branch"
        )
        results = program.run(num_shots=3)
        for shot in range(3):
            assert any(
                "logical_measurement" in frame
                for frame in results.shot_histories[shot]
            )

    def test_ft_prep_deep_spotcheck(self):
        stack_ftprep_D3X_error = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            # Here we inject an X error before layer 2, i.e. between CZs, on qubit 4 (0-indexed, and our qubit convention is 2 aux + 5 data)
            {
                "instruction": "Non-FT Minus Prep + Checks",
                "patch_label": "L0",
                "error_injections": [(2, "Gxpi", 4)],
            },
            # The RUS should do a check, then see that it failed, and do it all again
            {
                "instruction": "FT Minus Prep",
                "patch_label": "L0",
                "error_injections": [(2, "Gxpi", 4)],
            },
            ("FT Logical X Measure", "L0"),
        ]

        program_ftprep_D3X_error = QuantumProgram.from_quantum_program(
            self.program, stack_ftprep_D3X_error
        )
        results = program_ftprep_D3X_error.run()
        assert _check_shot_features(
            results,
            collect_shot_data_args=[
                {
                    "key": "measurement_outcomes",
                    "indices": 0,
                    "frame_filter": {
                        "log": "Non-FT Minus Prep + Checks result"
                    },
                },  # Let's grab the outcomes for the first round of RUS
                {
                    "key": "rus_success",
                    "indices": 0,
                    "frame_filter": {
                        "log": "Repeat-until-success FT Minus Prep result"
                    },
                },  # And also the computed RUS success value
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "Non-FT Minus Prep + Checks result"
                    },
                },  # Let's do it again for the second round
                {
                    "key": "rus_success",
                    "indices": -1,
                    "frame_filter": {
                        "log": "Repeat-until-success FT Minus Prep result"
                    },
                },
                (
                    "logical_measurement",
                    -1,
                ),  # And still check the logical outcome
            ],
            expected_outcomes=[
                MeasurementOutcomes({"A0": [0, 0, 1], "A1": [0, 0, 0]}),
                False,
                MeasurementOutcomes({"A0": [0, 0, 0], "A1": [0, 0, 0]}),
                True,
                1,
            ],
        )

    def test_ft_meas_deep_spotcheck(self):
        stack_ftmeas_partI_D2Z_error = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            ("FT Minus Prep", "L0"),
            # Insert at layer 0, a Z error, on qubit 3 (0-indexed, where first 2 are aux qubits)
            {
                "instruction": "FT Logical X Measure Part I Circuit",
                "patch_label": "L0",
                "error_injections": [(0, "Gzpi", 3)],
            },
            ("FT Logical X Measure Part I Feed-Forward", "L0"),
        ]

        program_ftmeas_partI_D2Z_error = QuantumProgram.from_quantum_program(
            self.program, stack_ftmeas_partI_D2Z_error
        )
        results = program_ftmeas_partI_D2Z_error.run()
        assert _check_shot_features(
            results,
            collect_shot_data_args=[
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Circuit result"
                    },
                },  # This should be all 0
                {
                    "key": "F1",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Feed-Forward result"
                    },
                },  # Should have no flag
                {
                    "key": "inferred_M1",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Feed-Forward result"
                    },
                },  # and this should have correctly identified logical 1 measurement
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part II Circuit result"
                    },
                },  # Now syndrome should be tripped
                {
                    "key": "F2",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part II Feed-Forward result"
                    },
                },  # Should have no flag
                {
                    "key": "inferred_M2",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part II Feed-Forward result"
                    },
                },  # but incorrectly identify logical 0 measurement
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "Non-FT state decoder circuit result"
                    },
                },  # The Z error should show up as a bitflip on data qubit 2
                {
                    "key": "classical_correction",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Classical Decoder result"
                    },
                },  # Remember that this is the decoded error
                {
                    "key": "corrected_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Classical Decoder result"
                    },
                },  # ... and applied the correction properly
                (
                    "logical_measurement",
                    -1,
                ),  # And still check the logical outcome
            ],
            expected_outcomes=[
                MeasurementOutcomes({"A0": [0], "A1": [0]}),
                0,
                1,
                MeasurementOutcomes({"A0": [1], "A1": [0]}),
                0,
                0,
                MeasurementOutcomes(
                    {"D2": [0], "D3": [1], "D4": [0], "D5": [0], "D6": [0]}
                ),
                "IXIII",
                [0, 0, 0, 0, 0],
                1,
            ],
            verbose=True,
        )

        stack_ftmeas_partI_M1X_error = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            ("FT Minus Prep", "L0"),
            # Insert at layer 3, a X error, on qubit 0 (0-indexed, where first qubit is measure qubit)
            {
                "instruction": "FT Logical X Measure Part I Circuit",
                "patch_label": "L0",
                "error_injections": [(3, "Gxpi", 0)],
            },
            ("FT Logical X Measure Part I Feed-Forward", "L0"),
        ]

        program_ftmeas_partI_M1X_error = QuantumProgram.from_quantum_program(
            self.program, stack_ftmeas_partI_M1X_error
        )
        results = program_ftmeas_partI_M1X_error.run()
        assert _check_shot_features(
            results,
            collect_shot_data_args=[
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Circuit result"
                    },
                },  # An X error is undetectable on measure, but it should trip the flag!
                {
                    "key": "F1",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Feed-Forward result"
                    },
                },  # We should have a flag...
                {
                    "key": "inferred_M1",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Part I Feed-Forward result"
                    },
                },  # ... but still think this is logical 1
                # The expected measurement outcome is non-trivial.
                # The X error on data qubit 1 will prop to Z errors on data qubit 2 and 5
                # This will cancel the Z error on data qubit 2, but show up as a bitflip on data qubit 5
                {
                    "key": "measurement_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "Non-FT state decoder circuit result"
                    },
                },
                {
                    "key": "classical_correction",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Classical Decoder result"
                    },
                },  # Remember that this is the decoded error
                {
                    "key": "corrected_outcomes",
                    "indices": -1,
                    "frame_filter": {
                        "log": "FT Logical X Measure Classical Decoder result"
                    },
                },
                (
                    "logical_measurement",
                    -1,
                ),  # And still check the logical outcome
            ],
            expected_outcomes=[
                MeasurementOutcomes({"A0": [0], "A1": [1]}),
                1,
                1,
                MeasurementOutcomes(
                    {"D2": [0], "D3": [0], "D4": [0], "D5": [0], "D6": [1]}
                ),
                "IIIIX",
                [0, 0, 0, 0, 0],
                1,
            ],
        )

    def test_h_syndrome_permutation(self):
        ref_program = self._create_program(
            PyGSTiPhysicalCircuit, DictNoiseModel, STIMQuantumState
        )
        stack = [
            {
                "instruction": "Init State",
                "state": len(self.qubits),
                "qubit_labels": self.qubits,
            },
            {
                "instruction": "Init Patch 5Q",
                "new_patch_label": "L0",
                "qubits": self.qubits,
            },
            {
                "instruction": "Non-FT Minus Prep",
                "patch_label": "L0",
                "error_injections": [(2, "Gzpi", 2)],
            },
            ("Unflagged QEC", "L0"),
            ("H", "L0"),
        ]
        program = QuantumProgram.from_quantum_program(ref_program, stack)
        results = program.run()
        history = results.shot_histories[0]
        h_frame = history[-1]
        assert "raw_syndrome" in h_frame
        assert h_frame["raw_syndrome"] == [0, 1, 1, 0]
