def _init_counter_from_seed(initial_value):
    """Apply function seeding a counter from the shot's own seed, so a
    shot's result can be tied back to its originating shot index."""
    return Frame({"counter": initial_value})


# A global instruction whose "initial_value" is sourced from the shot's
# own seed, so each shot's result depends on its own index.
_SEED_COUNTER_INSTRUCTION = Instruction(
    _init_counter_from_seed,
    param_priorities={"initial_value": ["program"]},
    param_aliases={"initial_value": "seed"},
    name="Initialize counter from shot seed",
)


class TestExecutorParallelism:
    """`QuantumProgram.run(shot_executor=...)`'s parallel path against a
    real `loky` executor: correctness (same outcomes as a serial run) and
    the thread-oversubscription discipline every worker must apply."""

    def _build_counter_program(self):
        trivial_code = trivial_codepack.create_qec_code()
        qubits = ["Q0"]
        ideal_model = trivial_codepack.create_ideal_model(qubits)
        stack = [
            {"instruction": "Init Patch Trivial", "new_patch_label": "L0", "qubits": qubits},
            {"instruction": "Init Counter From Seed"},
            {"instruction": "Increment", "patch_label": "L0", "increment_by": 1},
        ]
        return QuantumProgram(
            stack,
            default_noise_model=ideal_model,
            patch_types={"Trivial": trivial_code},
            global_instructions={
                "Init Counter From Seed": _SEED_COUNTER_INSTRUCTION
            },
            default_base_seed=0,
            name="executor parallelism test",
        )

    def test_loky_executor_matches_serial_shot_outcomes(self):
        # Each shot's counter is seeded from its own index, so comparing
        # per-index counters also confirms results land under the right index.
        loky = pytest.importorskip("loky")

        num_shots = 4
        serial_results = self._build_counter_program().run(
            num_shots=num_shots, verbose=False
        )

        executor = loky.get_reusable_executor(max_workers=2)
        parallel_results = self._build_counter_program().run(
            num_shots=num_shots, shot_executor=executor, verbose=False
        )

        serial_counters = {
            i: h[-1]["counter"]
            for i, h in serial_results.shot_histories.items()
        }
        parallel_counters = {
            i: h[-1]["counter"]
            for i, h in parallel_results.shot_histories.items()
        }
        assert parallel_counters == serial_counters == {
            i: i + 1 for i in range(num_shots)
        }

    def test_n_shot_batches_auto_default_dispatches_correct_batch_count(
        self, tmp_path
    ):
        """With shot_executor set and n_shot_batches=None, the auto-computed
        batch count is actually used to determine how many times
        shot_executor.submit() gets called during a real run() -- not just
        that the arithmetic function returns the right numbers in isolation."""
        loky = pytest.importorskip("loky")

        class SubmitCountingExecutor:
            """Wrapper around a real executor that counts .submit() calls."""

            def __init__(self, real_executor):
                self._real = real_executor
                self.submit_count = 0

            def submit(self, fn, *args, **kwargs):
                """Count this call and delegate to the real executor."""
                self.submit_count += 1
                return self._real.submit(fn, *args, **kwargs)

            def shutdown(self, wait=True):
                """Delegate to the real executor."""
                self._real.shutdown(wait=wait)

        # Set up a checkpoint directory
        checkpoint_dir = tmp_path / "checkpoint"
        checkpoint_dir.mkdir()

        # Build a simple program
        program = self._build_counter_program()

        # Create a counting wrapper around a real loky executor
        real_executor = loky.get_reusable_executor(max_workers=2)
        counting_executor = SubmitCountingExecutor(real_executor)

        try:
            # Run with num_shots=25, n_shot_batches=None (auto-default case),
            # and checkpoint=True. Auto-default for n_shot_batches should be
            # ceil(25/20) = 2 batches.
            results = program.run(
                num_shots=25,
                shot_executor=counting_executor,
                n_shot_batches=None,
                checkpoint=True,
                checkpoint_dir=checkpoint_dir,
                checkpoint_batch_size=None,  # Will auto-default to ceil(25/20)=2
                lazy_loading=False,
                verbose=False,
            )

            # Verify the run completed successfully with all 25 shots
            assert len(results.shot_histories) == 25

            # Verify submit() was called exactly 2 times (for 2 batches)
            assert (
                counting_executor.submit_count == 2
            ), f"Expected 2 submit() calls for ceil(25/20) batches, got {counting_executor.submit_count}"

            # Verify the results are sensible (counter values match shot indices)
            shot_counters = {i: h[-1]["counter"] for i, h in results.shot_histories.items()}
            assert shot_counters == {i: i + 1 for i in range(25)}
        finally:
            real_executor.shutdown(wait=True)


