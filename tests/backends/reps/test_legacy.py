"""Tester for loqs.backends.reps.legacy

This is the regression oracle for LoQS#72's decode-only compatibility
shim: `tests/backends/fixtures/reps_v1.{json,h5}` are frozen, pre-refactor
bytes (generated by `generate_reps_fixtures.py` from the old `RepTuple`/
`GateRep`/`InstrumentRep` enum-based code, before this refactor), and
decoding them against the *current* code is the only way to confirm old
`.json`/`.h5` files continue to load correctly. `reps_v2.{json,h5}` are a
frozen snapshot of the current format, kept as the known-good file to
validate a future redirect against.
"""

import json
from pathlib import Path

import h5py
import numpy as np
import pytest

from loqs.backends.reps import (
    KrausGateRep,
    OperationRep,
    PTMGateRep,
    ProbabilisticStimGateRep,
    QSimSuperopGateRep,
    StimCircuitGateRep,
    StimCircuitInstrumentRep,
    UnitaryGateRep,
    OutcomeOperationDictInstrumentRep,
    ZBasisPrePostInstrumentRep,
    ZBasisProjectionInstrumentRep,
)
from loqs.backends.reps.legacy import (
    upgrade_legacy_gaterep_tag,
    upgrade_legacy_instrumentrep_tag,
)
from loqs.internal.serializable import Serializable

FIXTURES_DIR = Path(__file__).parent.parent / "fixtures"


def _decode_fixture(version, fmt):
    if fmt == "json":
        with open(FIXTURES_DIR / f"reps_{version}.json") as f:
            return Serializable.decode(json.load(f), format="json")
    with h5py.File(FIXTURES_DIR / f"reps_{version}.h5", "r") as f:
        return Serializable.decode(f["root"], format="hdf5")


class TestRepsFixtureRoundTrip:
    """Round-trip `tests/backends/fixtures/reps_{v1,v2}.{json,h5}` to
    confirm every `GateRep`/`InstrumentRep` member decodes directly to the
    correct concrete class. The v1 files (generated pre-refactor) include
    two nested-`RepTuple` cases; `RepTuple` itself has been removed, and
    decode redirects straight to `OperationRep._from_decoded_attrs` via
    `IMPORT_LOCATION_CHANGES_BY_VERSION`."""

    EXPECTED_CLASSES = {
        "GATEREP_UNITARY": UnitaryGateRep,
        "GATEREP_PTM": PTMGateRep,
        "GATEREP_QSIM_SUPEROPERATOR": QSimSuperopGateRep,
        "GATEREP_STIM_CIRCUIT_STR": StimCircuitGateRep,
        "GATEREP_PROBABILISTIC_STIM_OPERATIONS": ProbabilisticStimGateRep,
        "GATEREP_KRAUS_OPERATORS": KrausGateRep,
        "INSTRUMENTREP_ZBASIS_PROJECTION": ZBasisProjectionInstrumentRep,
        "INSTRUMENTREP_ZBASIS_PRE_POST_OPERATIONS": ZBasisPrePostInstrumentRep,
        "INSTRUMENTREP_ZBASIS_OUTCOME_OPERATION_DICT": (
            OutcomeOperationDictInstrumentRep
        ),
        "INSTRUMENTREP_STIM_CIRCUIT_STR": StimCircuitInstrumentRep,
    }

    @pytest.fixture(
        params=[
            ("v1", "json"),
            ("v1", "hdf5"),
            ("v2", "json"),
            ("v2", "hdf5"),
        ],
        ids=["v1-json", "v1-hdf5", "v2-json", "v2-hdf5"],
    )
    def decoded(self, request):
        return _decode_fixture(*request.param)

    def test_all_members_present_with_correct_class(self, decoded):
        assert set(decoded.keys()) == set(self.EXPECTED_CLASSES.keys())
        for name, expected_cls in self.EXPECTED_CLASSES.items():
            rep = decoded[name]
            assert type(rep) is expected_cls
            assert rep.qubit_labels == ("Q0",)

    def test_flat_gate_rep_payloads_round_trip(self, decoded):
        assert decoded["GATEREP_STIM_CIRCUIT_STR"].circuit_str == "X 0"
        assert decoded["INSTRUMENTREP_STIM_CIRCUIT_STR"].circuit_str == "M 0"
        probs = decoded["GATEREP_PROBABILISTIC_STIM_OPERATIONS"].operations
        assert tuple(probs) == (("X 0", 0.5), ("Y 0", 0.5))
        kraus = decoded["GATEREP_KRAUS_OPERATORS"].kraus_operators
        assert len(kraus) == 2
        for op, prob in kraus:
            assert isinstance(op, np.ndarray)
            assert op.shape == (2, 2)
            assert prob is None
        assert isinstance(decoded["GATEREP_UNITARY"].unitary, np.ndarray)
        assert decoded["GATEREP_UNITARY"].unitary.shape == (2, 2)
        assert decoded["GATEREP_PTM"].ptm.shape == (4, 4)
        assert decoded["GATEREP_QSIM_SUPEROPERATOR"].superop.shape == (4, 4)

    def test_nested_pre_post_operations_round_trip(self, decoded):
        rep = decoded["INSTRUMENTREP_ZBASIS_PRE_POST_OPERATIONS"]
        assert rep.reset == 0
        assert rep.include_outcome == True  # noqa: E712
        assert isinstance(rep.pre_op, UnitaryGateRep)
        assert isinstance(rep.post_op, UnitaryGateRep)
        assert rep.pre_op.qubit_labels == ("Q0",)
        assert rep.post_op.qubit_labels == ("Q0",)


class TestRepsV1NestedOutcomeOperationDict:
    @pytest.mark.parametrize("fmt", ["json", "hdf5"])
    def test_nested_outcome_operation_dict_round_trip(self, fmt):
        """JSON round-trips the `{0: ..., 1: ...}` outcome dict's keys as
        *strings* (`"0"`, `"1"`), an inherent JSON limitation (object keys
        are always strings). HDF5 preserves the original int keys.
        """
        decoded = _decode_fixture("v1", fmt)
        rep = decoded["INSTRUMENTREP_ZBASIS_OUTCOME_OPERATION_DICT"]
        assert rep.include_outcome == True  # noqa: E712
        if fmt == "json":
            assert set(rep.outcome_ops.keys()) == {"0", "1"}
            outcome_0, outcome_1 = rep.outcome_ops["0"], rep.outcome_ops["1"]
        else:
            assert set(rep.outcome_ops.keys()) == {0, 1}
            outcome_0, outcome_1 = rep.outcome_ops[0], rep.outcome_ops[1]
        assert isinstance(outcome_0, PTMGateRep)
        assert isinstance(outcome_1, QSimSuperopGateRep)


class TestLegacyGaterepValueUpgrade:
    """Directly exercise `upgrade_legacy_gaterep_tag`, used by
    `DictNoiseModel._from_decoded_attrs` to translate old bare
    `GateRep`/`InstrumentRep` enum-member tags (as found in `_gatereps`/
    `_instreps`, never wrapped in a `RepTuple`) into modern classes."""

    @pytest.mark.parametrize("family", ["gate", "instrument"])
    def test_upgrades_every_legacy_value(self, family):
        from loqs.backends.reps.legacy import (
            _LegacyGateRepValue,
            _LegacyInstrumentRepValue,
        )

        if family == "gate":
            expected = {
                _LegacyGateRepValue.UNITARY: UnitaryGateRep,
                _LegacyGateRepValue.PTM: PTMGateRep,
                _LegacyGateRepValue.QSIM_SUPEROPERATOR: QSimSuperopGateRep,
                _LegacyGateRepValue.STIM_CIRCUIT_STR: StimCircuitGateRep,
                _LegacyGateRepValue.PROBABILISTIC_STIM_OPERATIONS: (
                    ProbabilisticStimGateRep
                ),
                _LegacyGateRepValue.KRAUS_OPERATORS: KrausGateRep,
            }
        else:
            expected = {
                _LegacyInstrumentRepValue.ZBASIS_PROJECTION: (
                    ZBasisProjectionInstrumentRep
                ),
                _LegacyInstrumentRepValue.ZBASIS_PRE_POST_OPERATIONS: (
                    ZBasisPrePostInstrumentRep
                ),
                _LegacyInstrumentRepValue.ZBASIS_OUTCOME_OPERATION_DICT: (
                    OutcomeOperationDictInstrumentRep
                ),
                _LegacyInstrumentRepValue.STIM_CIRCUIT_STR: (
                    StimCircuitInstrumentRep
                ),
            }
        for legacy_value, expected_cls in expected.items():
            assert upgrade_legacy_gaterep_tag(legacy_value) is expected_cls

    @pytest.mark.parametrize("family", ["gate", "instrument"])
    def test_bare_int_resolved_in_its_family(self, family):
        """`SERIALIZATION_VERSION` 0 (the original, pre-HDF5 JSON format)
        encoded entries as bare `int`s with no `(module, class)` metadata
        to tell `GateRep` from `InstrumentRep`, so each helper resolves a
        bare int within the family its caller (`_gatereps` or `_instreps`)
        belongs to."""
        if family == "gate":
            assert upgrade_legacy_gaterep_tag(1) is UnitaryGateRep
            assert upgrade_legacy_gaterep_tag(6) is KrausGateRep
        else:
            assert (
                upgrade_legacy_instrumentrep_tag(1)
                is ZBasisProjectionInstrumentRep
            )
            assert (
                upgrade_legacy_instrumentrep_tag(4) is StimCircuitInstrumentRep
            )


class TestLegacyValueDecoding:
    """Directly exercise `GateRep._from_decoded_attrs`'s legacy-tag
    special-casing, without going through a full `RepTuple`-wrapped
    fixture."""

    def test_concrete_gaterep_subclass_does_not_use_legacy_path(self):
        """A concrete subclass's `_from_decoded_attrs` (inherited from
        `GateRep`, unmodified) should fall through to normal
        `Serializable`-style construction, not the legacy-tag branch,
        since `cls is GateRep` is only true for the literal abstract
        base."""
        result = UnitaryGateRep._from_decoded_attrs(
            {"unitary": np.eye(2), "qubits": ("Q0",)}
        )
        assert isinstance(result, UnitaryGateRep)
        assert np.array_equal(result.unitary, np.eye(2))
        assert result.qubit_labels == ("Q0",)


